package pl.aiwcorpo.mcp.manifest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

/** The Java filter must reproduce the vectors generated by scripts/lib/endpoint-filter.mjs. */
class EndpointFilterVectorTest {

    private static final ObjectMapper JSON = new ObjectMapper();

    static Stream<Path> vectors() {
        return ContractFiles.list("test-vectors/endpoint-filter", ".json").stream();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("vectors")
    void matchesJavaScript(Path file) throws Exception {
        JsonNode v = JSON.readTree(file.toFile());
        JsonNode input = v.get("input");
        JsonNode expected = v.get("expected");
        switch (v.get("kind").asText()) {
            case "parse" -> parse(file, input, expected);
            case "route" -> route(file, input, expected);
            case "apply" -> apply(file, input, expected);
            case "call" -> call(file, input, expected);
            case "session" -> session(file, input, expected);
            // The state checks of tools/call and the order of the checks of a session are decisions of the gateway, not of the
            // filter; the reference in scripts/lib/endpoint-filter.mjs and the Node tests cover them.
            case "error-response", "call-state", "session-order", "stream-open" -> { }
            default -> throw new IllegalStateException(file.toString());
        }
    }

    private static void parse(Path file, JsonNode input, JsonNode expected) {
        String query = input.get("query").asText();
        if (expected.get("valid").asBoolean()) {
            EndpointFilter filter = EndpointFilter.parse(query);
            assertEquals(expected.get("canonical").asText(), filter.canonical(), file::toString);
            JsonNode f = expected.get("filter");
            assertEquals(list(f.get("systems")), filter.systems(), file::toString);
            assertEquals(list(f.get("tools")), filter.tools(), file::toString);
            assertEquals(list(f.get("exclude")), filter.exclude(), file::toString);
            assertEquals(f.get("access").isNull() ? java.util.Optional.empty() : java.util.Optional.of(f.get("access").asText()),
                    filter.access().map(a -> a.name().toLowerCase(java.util.Locale.ROOT)), file::toString);
        } else {
            var e = assertThrows(EndpointFilter.Invalid.class, () -> EndpointFilter.parse(query), file::toString);
            assertEquals(expected.get("cause").asText(), e.cause(), file::toString);
        }
    }

    private static java.util.Optional<List<String>> list(JsonNode node) {
        if (node.isNull()) {
            return java.util.Optional.empty();
        }
        List<String> out = new ArrayList<>();
        node.forEach(n -> out.add(n.asText()));
        return java.util.Optional.of(out);
    }

    private static void route(Path file, JsonNode input, JsonNode expected) {
        String routeSystem = input.get("routeSystem").isNull() ? null : input.get("routeSystem").asText();
        String query = input.get("query").asText();
        if (expected.get("valid").asBoolean()) {
            EndpointFilter filter = EndpointFilter.parse(query);
            filter.checkRoute(routeSystem);
            assertEquals(expected.get("canonical").asText(), filter.canonical(), file::toString);
        } else {
            var e = assertThrows(EndpointFilter.Invalid.class, () -> EndpointFilter.parse(query).checkRoute(routeSystem), file::toString);
            assertEquals(expected.get("cause").asText(), e.cause(), file::toString);
        }
    }

    private static List<String> visible(EndpointFilter filter, JsonNode tools) {
        List<String> out = new ArrayList<>();
        tools.forEach(t -> {
            if (filter.allows(t.get("name").asText(), t.get("risk").asText())) {
                out.add(t.get("name").asText());
            }
        });
        return out;
    }

    private static void apply(Path file, JsonNode input, JsonNode expected) {
        EndpointFilter filter = EndpointFilter.parse(input.get("query").asText());
        assertEquals(expected.get("canonical").asText(), filter.canonical(), file::toString);
        List<String> want = new ArrayList<>();
        expected.get("visible").forEach(n -> want.add(n.asText()));
        assertEquals(want, visible(filter, input.get("tools")), file::toString);
    }

    private static void call(Path file, JsonNode input, JsonNode expected) {
        EndpointFilter filter = EndpointFilter.parse(input.get("query").asText());
        String tool = input.get("tool").asText();
        boolean allowed = visible(filter, input.get("tools")).contains(tool);
        assertEquals("allowed".equals(expected.get("outcome").asText()), allowed, file::toString);
        if (!allowed) {
            Set<String> mayCall = new java.util.HashSet<>();
            input.get("mayCall").forEach(n -> mayCall.add(n.asText()));
            assertEquals(expected.get("auditReason").asText(), mayCall.contains(tool) ? "filter_scope" : "not_granted", file::toString);
        }
    }

    private static void session(Path file, JsonNode input, JsonNode expected) {
        assertEquals(expected.get("match").asBoolean(),
                EndpointFilter.sessionMatches(input.get("initializeQuery").asText(), input.get("requestQuery").asText()), file::toString);
    }

    @Test
    void thereAreVectorsOfEveryKind() {
        List<String> kinds = vectors().map(file -> {
            try {
                return JSON.readTree(file.toFile()).get("kind").asText();
            } catch (java.io.IOException e) {
                throw new IllegalStateException(e);
            }
        }).distinct().sorted().toList();
        assertEquals(List.of("apply", "call", "call-state", "error-response", "parse", "route", "session", "session-order", "stream-open"), kinds);
    }

    @Test
    void aRiskOutsideTheClosedSetIsLeftOutByBothAccessValues() {
        for (String risk : new String[] {"UNKNOWN", "read_only", "", null}) {
            assertFalse(EndpointFilter.parse("access=read").allows("jira__legacy_tool", risk), String.valueOf(risk));
            assertFalse(EndpointFilter.parse("access=write").allows("jira__legacy_tool", risk), String.valueOf(risk));
            assertTrue(EndpointFilter.parse("systems=jira").allows("jira__legacy_tool", risk), String.valueOf(risk));
        }
    }

    @Test
    void emptyFilterAllowsEverything() {
        EndpointFilter none = EndpointFilter.none();
        assertTrue(none.isEmpty());
        assertTrue(none.allows("jira__delete_issue", "DESTRUCTIVE"));
        assertEquals("", none.canonical());
    }
}
