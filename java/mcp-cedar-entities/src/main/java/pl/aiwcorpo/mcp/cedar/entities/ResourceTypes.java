package pl.aiwcorpo.mcp.cedar.entities;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.TreeSet;
import java.util.regex.Pattern;
import java.util.regex.PatternSyntaxException;
import pl.aiwcorpo.mcp.cedar.entities.ResourceTypeDeclaration.Classification;
import pl.aiwcorpo.mcp.cedar.entities.ResourceTypeDeclaration.Kind;

/**
 * The resource types the builder knows: the declarations of the registered servers, nothing built in. The gateway
 * builds one registry from the manifests of all registered servers ({@link #union}); a server builds it from its own
 * manifest. Immutable and thread-safe; build a new one when the set of servers or a manifest changes.
 *
 * <p>Patterns use the common subset of Java and ECMAScript regular expressions (the contract vectors are generated by a
 * JavaScript builder and executed here); they are matched against the whole id.
 */
public final class ResourceTypes {

    private static final Pattern TYPE = Pattern.compile("^[A-Z][A-Za-z0-9]{0,30}::[A-Z][A-Za-z0-9]{0,30}$");
    private static final Pattern ATTRIBUTE = Pattern.compile("^[a-z][A-Za-z0-9]*$");
    private static final ResourceTypes EMPTY = new ResourceTypes(Map.of());
    private static final ObjectMapper JSON = new ObjectMapper();

    private record Compiled(ResourceTypeDeclaration declaration, Pattern id, Pattern scope) {
    }

    private final Map<String, Compiled> byType;

    private ResourceTypes(Map<String, Compiled> byType) {
        this.byType = byType;
    }

    /** @return a registry without any type: every resource type is unknown */
    public static ResourceTypes empty() {
        return EMPTY;
    }

    /**
     * @throws IllegalArgumentException when a declaration is malformed or the set is inconsistent (duplicate type,
     *         undeclared parent, a pattern that is not anchored or does not compile, ...)
     */
    public static ResourceTypes of(Collection<ResourceTypeDeclaration> declarations) {
        Map<String, ResourceTypeDeclaration> declared = new LinkedHashMap<>();
        for (ResourceTypeDeclaration declaration : declarations) {
            if (declared.put(declaration.type(), declaration) != null) {
                throw new IllegalArgumentException("resource type declared twice: " + declaration.type());
            }
        }
        Map<String, Compiled> compiled = new LinkedHashMap<>();
        for (ResourceTypeDeclaration d : declared.values()) {
            check(d, declared);
            compiled.put(d.type(), new Compiled(d, anchored(d.type(), "idPattern", d.idPattern()),
                    d.scopePattern().map(p -> anchored(d.type(), "scopePattern", p)).orElse(null)));
        }
        return new ResourceTypes(Collections.unmodifiableMap(compiled));
    }

    /**
     * Registry of several servers. A namespace belongs to one server: two registries that declare types of the same
     * namespace are an error (the gateway answers {@code namespace_conflict}), also when the types differ, because a
     * second server could otherwise add types to the namespace of the first and be granted scopes meant for it.
     *
     * @throws IllegalArgumentException when a namespace appears in two registries; the caller must treat it as a deny
     */
    public static ResourceTypes union(Collection<ResourceTypes> registries) {
        List<ResourceTypeDeclaration> all = new ArrayList<>();
        java.util.Set<String> seen = new java.util.HashSet<>();
        for (ResourceTypes registry : registries) {
            java.util.Set<String> own = new java.util.TreeSet<>();
            registry.declarations().forEach(d -> own.add(d.namespace()));
            for (String namespace : own) {
                if (!seen.add(namespace)) {
                    throw new IllegalArgumentException("namespace_conflict: " + namespace + " is declared by two servers");
                }
            }
            all.addAll(registry.declarations());
        }
        return of(all);
    }

    /** Ids and local scope parts longer than this are invalid before any pattern is applied. */
    public static final int MAX_ID_LENGTH = pl.aiwcorpo.mcp.manifest.PatternGrammar.MAX_ID_LENGTH;

    /** Longest {@code idPattern} or {@code scopePattern}. */
    public static final int MAX_PATTERN_LENGTH = pl.aiwcorpo.mcp.manifest.PatternGrammar.MAX_PATTERN_LENGTH;

    /**
     * Reads the {@code resourceTypes} array of a manifest, e.g.
     * {@code [{"type":"Notes::Notebook","attributes":["name"],"idPattern":"^[a-z0-9]{1,16}$"}]}.
     *
     * @throws IllegalArgumentException when the JSON is not a valid array of declarations
     */
    public static ResourceTypes fromJson(String json) {
        try {
            JsonNode array = JSON.readTree(json);
            if (array == null || !array.isArray()) {
                throw new IllegalArgumentException("resourceTypes must be a JSON array");
            }
            List<ResourceTypeDeclaration> declarations = new ArrayList<>();
            for (JsonNode node : array) {
                declarations.add(declaration(node));
            }
            return of(declarations);
        } catch (IOException e) {
            throw new IllegalArgumentException("resourceTypes is not valid JSON: " + e.getMessage(), e);
        }
    }

    private static ResourceTypeDeclaration declaration(JsonNode node) {
        List<String> attributes = new ArrayList<>();
        node.path("attributes").forEach(a -> attributes.add(a.asText()));
        Optional<Classification> classification = node.has("classification")
                ? Optional.of(new Classification(node.get("classification").path("attribute").asText(),
                        "set".equals(node.get("classification").path("kind").asText()) ? Kind.SET : kindOfString(node),
                        node.get("classification").path("required").asBoolean(false)))
                : Optional.empty();
        return new ResourceTypeDeclaration(node.path("type").asText(), attributes, text(node, "parent"),
                text(node, "parentAttribute"), node.path("idPattern").asText(), text(node, "scopePattern"),
                node.path("earlyScopeCheck").asBoolean(false), classification);
    }

    private static Kind kindOfString(JsonNode node) {
        String kind = node.get("classification").path("kind").asText();
        if (!"string".equals(kind)) {
            throw new IllegalArgumentException(node.path("type").asText() + ": classification.kind must be string or set");
        }
        return Kind.STRING;
    }

    private static Optional<String> text(JsonNode node, String field) {
        return node.has(field) && !node.get(field).isNull() ? Optional.of(node.get(field).asText()) : Optional.empty();
    }

    private static void check(ResourceTypeDeclaration d, Map<String, ResourceTypeDeclaration> declared) {
        if (!TYPE.matcher(d.type()).matches()) {
            throw new IllegalArgumentException("not a resource type: " + d.type());
        }
        if (new TreeSet<>(d.attributes()).size() != d.attributes().size()) {
            throw new IllegalArgumentException(d.type() + ": attributes are not unique");
        }
        for (String attribute : d.attributes()) {
            if (!ATTRIBUTE.matcher(attribute).matches() || "scopes".equals(attribute)) {
                throw new IllegalArgumentException(d.type() + ": attribute not allowed: " + attribute);
            }
        }
        if (d.parent().isPresent() != d.parentAttribute().isPresent()) {
            throw new IllegalArgumentException(d.type() + ": parent and parentAttribute go together");
        }
        if (d.parent().isPresent()) {
            ResourceTypeDeclaration parent = declared.get(d.parent().get());
            if (parent == null || !parent.namespace().equals(d.namespace())) {
                throw new IllegalArgumentException(d.type() + ": parent " + d.parent().get() + " is not declared in the same namespace");
            }
            String attribute = d.parentAttribute().get();
            if (!ATTRIBUTE.matcher(attribute).matches() || "scopes".equals(attribute) || d.attributes().contains(attribute)) {
                throw new IllegalArgumentException(d.type() + ": parentAttribute not allowed: " + attribute);
            }
        }
        if (d.earlyScopeCheck() && d.scopePattern().isEmpty()) {
            throw new IllegalArgumentException(d.type() + ": earlyScopeCheck needs a scopePattern");
        }
        d.classification().ifPresent(c -> {
            if (!d.attributes().contains(c.attribute())) {
                throw new IllegalArgumentException(d.type() + ": classification attribute is not in attributes: " + c.attribute());
            }
        });
    }

    private static Pattern anchored(String type, String field, String regex) {
        String violation = pl.aiwcorpo.mcp.manifest.PatternGrammar.violation(regex);
        if (violation != null) {
            throw new IllegalArgumentException(type + ": " + field + " is outside the allowed grammar: " + violation);
        }
        if (!isAnchored(regex)) {
            throw new IllegalArgumentException(type + ": " + field + " must be anchored with ^ and $");
        }
        try {
            return Pattern.compile(regex);
        } catch (PatternSyntaxException e) {
            throw new IllegalArgumentException(type + ": " + field + " does not compile: " + e.getDescription(), e);
        }
    }

    /**
     * Anchored means: starts with {@code ^}, ends with an unescaped {@code $} and has no alternation outside every
     * group, so that {@code ^a|b$} (which matches any string containing b) is not accepted. Same rule as the manifest
     * rules for {@code inputSchema} patterns (CC-123).
     */
    static boolean isAnchored(String regex) {
        if (!regex.startsWith("^") || !regex.endsWith("$")) {
            return false;
        }
        int backslashes = 0;
        for (int i = regex.length() - 2; i >= 0 && regex.charAt(i) == '\\'; i--) {
            backslashes++;
        }
        if (backslashes % 2 == 1) {
            return false;
        }
        int depth = 0;
        boolean inClass = false;
        for (int i = 0; i < regex.length(); i++) {
            char c = regex.charAt(i);
            if (c == '\\') {
                i++;
            } else if (inClass) {
                inClass = c != ']';
            } else if (c == '[') {
                inClass = true;
            } else if (c == '(') {
                depth++;
            } else if (c == ')') {
                depth--;
            } else if (c == '|' && depth == 0) {
                return false;
            }
        }
        return true;
    }

    /** @return whether a server declared the type */
    public boolean isDeclared(String type) {
        return byType.containsKey(type);
    }

    /** @return the declaration of the type */
    public Optional<ResourceTypeDeclaration> declaration(String type) {
        return Optional.ofNullable(byType.get(type)).map(Compiled::declaration);
    }

    /** @return every declaration, in declaration order */
    public List<ResourceTypeDeclaration> declarations() {
        return byType.values().stream().map(Compiled::declaration).toList();
    }

    /** @return true when the type is declared and {@code id} matches its {@code idPattern} as a whole; false otherwise */
    public boolean isValidId(String type, String id) {
        Compiled compiled = byType.get(type);
        return compiled != null && id != null && id.length() <= MAX_ID_LENGTH && compiled.id().matcher(id).matches();
    }

    /** @return true when the type is declared, can be granted, and {@code localId} matches its {@code scopePattern} */
    public boolean isValidScopeLocalId(String type, String localId) {
        Compiled compiled = byType.get(type);
        return compiled != null && compiled.scope() != null && localId != null && localId.length() <= MAX_ID_LENGTH
                && compiled.scope().matcher(localId).matches();
    }

    /** @return whether the type can be granted in the scope mapping */
    public boolean isGrantable(String type) {
        Compiled compiled = byType.get(type);
        return compiled != null && compiled.scope() != null;
    }

    /** @return whether the gateway checks an argument of this type against {@code principal.scopes} before the call */
    public boolean isEarlyScopeCheck(String type) {
        Compiled compiled = byType.get(type);
        return compiled != null && compiled.declaration().earlyScopeCheck();
    }

    /**
     * Splits a scope id {@code <Type>/<local>} and checks it against the declarations.
     *
     * @return the type, empty when the id is malformed, the type is not declared or not grantable, or the local part
     *         does not match its {@code scopePattern}
     */
    public Optional<String> scopeType(String scopeId) {
        int slash = scopeId.indexOf('/');
        if (slash <= 0 || slash == scopeId.length() - 1) {
            return Optional.empty();
        }
        String type = scopeId.substring(0, slash);
        return isValidScopeLocalId(type, scopeId.substring(slash + 1)) ? Optional.of(type) : Optional.empty();
    }

    /** @return the part after the type, e.g. {@code team-a/sub} for {@code GitLab::Group/team-a/sub} */
    public static String localId(String scopeId) {
        return scopeId.substring(scopeId.indexOf('/') + 1);
    }

    @Override
    public String toString() {
        return "ResourceTypes" + Objects.toString(byType.keySet());
    }
}
