// Builds dist/: TypeScript types from the OpenAPI documents and JSON Schemas, and the compiled MSW handlers.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import openapiTS, { astToString } from 'openapi-typescript';
import { compileFromFile } from 'json-schema-to-typescript';
import { pathToFileURL } from 'node:url';
import { OPENAPI_FILES, path, schemaFiles } from './lib/contracts.mjs';
import { bundledName } from './bundle-openapi.mjs';

const VERSION = JSON.parse(readFileSync(path('package.json'), 'utf8')).version;
const BANNER = `/* Generated by scripts/build-npm.mjs from mcp-contracts ${VERSION}. Do not edit. */`;

rmSync(path('dist'), { recursive: true, force: true });
mkdirSync(path('dist', 'types', 'schemas'), { recursive: true });

for (const file of OPENAPI_FILES) {
  const ast = await openapiTS(pathToFileURL(path('openapi', 'bundled', bundledName(file))), {
    // Fields with a default stay optional in the types: a missing `enabled` means true (CC-088), not false.
    defaultNonNullable: false,
  });
  writeFileSync(path('dist', 'types', file.replace(/\.yaml$/, '.d.ts')), `${BANNER}\n${astToString(ast)}`);
}

for (const file of schemaFiles()) {
  if (file === 'common.schema.json') continue;
  const ts = await compileFromFile(path('schemas', file), {
    cwd: path('schemas'),
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: false,
  });
  writeFileSync(path('dist', 'types', 'schemas', file.replace(/\.schema\.json$/, '.d.ts')), ts);
}

execFileSync(path('node_modules', '.bin', 'tsc'), ['-p', path('tsconfig.json')], { stdio: 'inherit' });
console.log('dist built');
