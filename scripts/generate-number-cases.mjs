// Writes the ECMAScript number cases used by mcp-manifest tests (powers of two and random doubles, review 2.0.0 M2).
// Usage: node scripts/generate-number-cases.mjs java/mcp-manifest/src/test/resources/ecmascript-numbers.json
import { writeFileSync } from 'node:fs';
const view = new DataView(new ArrayBuffer(8));
const cases = [];
const add = (d) => { view.setFloat64(0, d); cases.push({ bits: view.getBigUint64(0).toString(16).padStart(16, '0'), canonical: String(d) }); };
for (let k = -1074; k <= 1023; k++) { const d = 2 ** k; add(d); add(-d); }
let seed = 0x9e3779b9;
const next = () => { seed ^= seed << 13; seed >>>= 0; seed ^= seed >>> 17; seed ^= seed << 5; seed >>>= 0; return seed; };
for (let i = 0; i < 5000; i++) { view.setUint32(0, next()); view.setUint32(4, next()); const d = view.getFloat64(0); if (Number.isFinite(d)) add(d); }
writeFileSync(process.argv[2], JSON.stringify({ description: 'Powers of two and random doubles with ECMAScript String(d), generated by Node for review 2.0.0 M2.', cases }) + '\n');
