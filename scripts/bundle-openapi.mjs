// Produces single-file OpenAPI documents in openapi/bundled/ for code generators.
// Sources keep $refs to ../schemas so that JSON Schema stays the single definition; generators such as
// openapi-generator name inline-resolved external types after the operation, so they get the bundle.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { bundle, createConfig } from '@redocly/openapi-core';
import YAML from 'yaml';
import { OPENAPI_FILES, path } from './lib/contracts.mjs';

const pascal = (name) => name.replace(/\.schema$/, '').split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

export async function bundleOpenApi(file) {
  const config = await createConfig({});
  const result = await bundle({ ref: path('openapi', file), config, dereference: false });
  const doc = result.bundle.parsed;
  const renames = Object.keys(doc.components?.schemas ?? {}).filter((n) => n.endsWith('.schema'));
  let text = JSON.stringify(doc);
  for (const from of renames) {
    const to = pascal(from);
    if (doc.components.schemas[to]) throw new Error(`${file}: bundled name clash ${to}`);
    text = text.replaceAll(`"#/components/schemas/${from}"`, `"#/components/schemas/${to}"`);
  }
  const renamed = JSON.parse(text);
  for (const from of renames) {
    const schemas = renamed.components.schemas;
    schemas[pascal(from)] = schemas[from];
    delete schemas[from];
    delete schemas[pascal(from)].$schema;
  }
  return '# Generated by scripts/bundle-openapi.mjs from openapi/' + file + '. Do not edit.\n'
    + YAML.stringify(renamed, { lineWidth: 0 });
}

export function bundledName(file) {
  return file.replace(/\.yaml$/, '.bundled.yaml');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(path('openapi', 'bundled'), { recursive: true });
  for (const file of OPENAPI_FILES) {
    writeFileSync(path('openapi', 'bundled', bundledName(file)), await bundleOpenApi(file));
    console.log(`openapi/bundled/${bundledName(file)}`);
  }
}
