// Generates WireMock stubs for C4 and C5 and the example table used by the MSW handlers for C12.
// Everything comes from the named examples in the OpenAPI documents, which npm test validates
// against the schemas, so a mock can never answer with something the contract does not allow.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dereferenceOpenApi, operations, path } from './lib/contracts.mjs';

const WIREMOCK_SPECS = {
  'credential-broker.v1.yaml': 'credential-broker',
  'gateway-admin.v1.yaml': 'gateway-admin',
};

function responsesOf(operation) {
  const out = [];
  for (const [status, response] of Object.entries(operation.responses)) {
    const media = response.content?.['application/json'];
    const examples = Object.entries(media?.examples ?? {});
    const location = Object.values(response.headers?.Location?.examples ?? {})[0]?.value;
    const headers = location ? { Location: location } : undefined;
    if (examples.length === 0) {
      out.push({ status: Number(status), name: `status-${status}`, body: undefined, ...(headers && { headers }) });
    } else {
      for (const [name, example] of examples) out.push({ status: Number(status), name, body: example.value });
    }
  }
  return out;
}

function needsBearer(operation) {
  return (operation.security ?? []).every((requirement) => Object.keys(requirement).some((k) => k !== 'mtls'));
}

export function operationExamples(spec) {
  const result = [];
  for (const { route, method, operation } of operations(spec)) {
    const responses = responsesOf(operation);
    const defaultResponse = responses.find((r) => r.status >= 200 && r.status < 400);
    result.push({
      operationId: operation.operationId,
      method: method.toUpperCase(),
      route,
      needsBearer: needsBearer(operation),
      defaultExample: defaultResponse.name,
      responses,
    });
  }
  return result;
}

function wiremockResponse({ status, body, headers }) {
  const response = { status, ...(headers && { headers }) };
  if (body !== undefined) {
    response.headers = { ...response.headers, 'Content-Type': 'application/json; charset=utf-8' };
    response.jsonBody = body;
  }
  return response;
}

function wiremockMappings(op) {
  const request = { method: op.method, urlPathTemplate: op.route };
  const auth = op.needsBearer ? { Authorization: { matches: '^Bearer .+$' } } : undefined;
  const mappings = [];
  if (op.needsBearer) {
    mappings.push({
      name: `${op.operationId} without bearer token`,
      priority: 1,
      request: { ...request, headers: { Authorization: { absent: true } } },
      response: { status: 401, headers: { 'Content-Type': 'application/json; charset=utf-8' }, jsonBody: { error: 'unauthenticated' } },
    });
  }
  for (const r of op.responses) {
    const isDefault = r.name === op.defaultExample;
    const headers = { ...auth };
    if (!isDefault) headers.Prefer = { matches: `(^|.*[ ,;])example=${r.name}($|[ ,;].*)` };
    mappings.push({
      name: `${op.operationId} ${r.status} ${r.name}`,
      priority: isDefault ? 5 : 2,
      request: { ...request, ...(Object.keys(headers).length > 0 && { headers }) },
      response: wiremockResponse(r),
    });
  }
  return mappings;
}

export async function generateWiremock() {
  const files = {};
  for (const [specFile, dir] of Object.entries(WIREMOCK_SPECS)) {
    const spec = await dereferenceOpenApi(specFile);
    for (const op of operationExamples(spec)) {
      files[`${dir}/mappings/${op.operationId}.json`] = JSON.stringify({ mappings: wiremockMappings(op) }, null, 2) + '\n';
    }
  }
  return files;
}

export async function generateMswExamples() {
  const spec = await dereferenceOpenApi('portal-bff.v1.yaml');
  const table = operationExamples(spec).map(({ needsBearer: _unused, ...op }) => op);
  const broker = await dereferenceOpenApi('credential-broker.v1.yaml');
  return '// Generated by scripts/generate-mocks.mjs from openapi/portal-bff.v1.yaml. Do not edit.\n'
    + 'import type { OperationExamples } from \'./types.js\';\n\n'
    + `export const RETURN_PATH_PATTERN = ${JSON.stringify(broker.components.schemas.ReturnPath.pattern)};\n\n`
    + `export const portalBffExamples: OperationExamples[] = ${JSON.stringify(table, null, 2)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  rmSync(path('mocks', 'wiremock'), { recursive: true, force: true });
  for (const [file, content] of Object.entries(await generateWiremock())) {
    const target = path('mocks', 'wiremock', file);
    mkdirSync(target.slice(0, target.lastIndexOf('/')), { recursive: true });
    writeFileSync(target, content);
  }
  mkdirSync(path('mocks', 'msw'), { recursive: true });
  writeFileSync(path('mocks', 'msw', 'portal-bff.examples.ts'), await generateMswExamples());
  console.log('mocks generated');
}
